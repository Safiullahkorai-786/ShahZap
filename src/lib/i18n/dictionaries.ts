// Catalog lookup with an English fallback for any language that has not been
// added yet (or for dictionary keys that are missing).
const CATALOGS: Record<string, Dict> = { en, ur, ar, hi }

export const SUPPORTED_UI_LANGS = ['en', 'ur', 'ar', 'hi'] as const

export function getDictionary(lang: string | null | undefined): Dict {
  return CATALOGS[lang ?? 'en'] ?? en
}

// RTL scripts for the supported UI languages.
const RTL = new Set(['ur', 'ar'])
export function isRtl(lang: string | null | undefined): boolean {
  return RTL.has(lang ?? '')
}
